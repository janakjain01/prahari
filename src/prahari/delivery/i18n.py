def language_name(code: str) -> str:
    return _LANGUAGE_NAMES.get(code, code)


def translate(key: str, language: str = "en", **kwargs: Any) -> str:
    """Look up ``key`` in ``language``, falling back to English.

    Falls back rather than raising: a missing translation should degrade to a
    language the reader may not prefer, never to a blank line or a stack trace
    in the middle of an evacuation notice.
    """
    table = LOCALES.get(language) or LOCALES["en"]
    template = table.get(key) or LOCALES["en"].get(key, key)
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def format_duration(minutes: float, language: str = "en") -> str:
    return f"{int(round(minutes))} {translate('minutes', language)}"
