"""Localisation for citizen-facing alerts.

Design decision worth defending: the action-card text is built from
PRE-TRANSLATED TEMPLATES with slot filling, not generated by an LLM at
request time.

Three reasons, in order of how much they matter:

  1. An emergency message must be deterministic. The same flood state must
     produce the same words every time. A generative model that paraphrases
     "do not take the main road" into something subtly weaker on one run is an
     unacceptable failure mode for a safety message.
  2. No network dependency at the moment of use. The venue wifi will fail; so
     will a district's connectivity during a flood. Templates work offline.
  3. Translations can be REVIEWED by a native speaker once, and then they stay
     reviewed. Generated text cannot be reviewed in advance because it does
     not exist yet.

An optional LLM path exists in ``action_card.py`` for drafting NEW template
strings during development. It is never on the live path.

HONEST CAVEAT, and it belongs in the pitch: these translations were prepared
by the team and have NOT yet been validated by a native Assamese speaker or by
ASDMA. Before any real deployment they must be. Alert wording is a
life-safety surface and "it looked right to us" is not a standard.
"""

